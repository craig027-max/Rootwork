#!/usr/bin/env python3
"""Bake short neural hear clips for Wondral Words.

Run from the repo root (not on the phone, not at app runtime):

    python3 scripts/generate-hear-clips.py
    python3 scripts/generate-hear-clips.py --tier 1

Uses Microsoft Edge neural TTS (en-US-JennyNeural) at generation time only.
Clips ship as static mp3s; Hear never calls a TTS API.
"""

from __future__ import annotations

import argparse
import asyncio
import re
import subprocess
import sys
import tempfile
from pathlib import Path

def _edge_tts():
    try:
        import edge_tts
    except ImportError:
        sys.stderr.write("Install edge-tts first: pip3 install edge-tts\n")
        sys.exit(1)
    return edge_tts

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "src" / "data" / "roots.data.ts"
OUT_DIR = ROOT / "public" / "audio" / "hear"
MANIFEST = ROOT / "src" / "core" / "hearClips.ts"

VOICE = "en-US-JennyNeural"
RATE = "-12%"
# Keep in lockstep with HEAR_BEAT_PAUSE in src/core/speak.ts.
# Jenny ignores extra periods / ellipses / newlines; the baker splits on this
# mark and inserts HEAR_BEAT_GAP_S of silence so name / sound / letters stay
# separate even when they sound alike (Geo / jee oh).
HEAR_BEAT_PAUSE = "…"
HEAR_BEAT_GAP_S = 0.6
# Drop leading / trailing pad on each beat so the inserted gap is the pause.
BEAT_TRIM_AF = (
    "silenceremove=start_periods=1:start_silence=0.04:start_threshold=-35dB,"
    "areverse,"
    "silenceremove=start_periods=1:start_silence=0.08:start_threshold=-35dB,"
    "areverse,"
    "aformat=sample_fmts=fltp:sample_rates=24000:channel_layouts=mono"
)
ROW = re.compile(r"\{\s*t:(\d+)\s*,\s*root:'([^']+)'\s*,\s*say:'([^']+)'")


